f = 'src/data/books/yingyao.ts'
s = io.open(f, encoding='utf-8').read()

def esc(x):
    return x.replace('\\', '\\\\').replace("'", "\\'")

out = []
current = 0
for line in s.split('\n'):
    m = re.match(r'^(\s*)no: (\d+),$', line)
    if m:
        current = int(m.group(2))
    # 在 text 行之后插入 trans
    if current in TRANS and line.rstrip().endswith("',"):
        out.append(line)
        out.append(f"{m.group(1) if m else '    '}trans: '{esc(TRANS[current])}',")
        continue
    out.append(line)

s = '\n'.join(out)
# 类型定义加 trans
s = s.replace("  text: string;\n  note: string;", "  text: string;\n  trans?: string;\n  note: string;")
io.open(f, 'w', encoding='utf-8').write(s)
print('inserted', len(TRANS), 'translations')
